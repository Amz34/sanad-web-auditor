#!/usr/bin/env node

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const { Command } = require('commander');

const program = new Command();

program
  .name('sanad-web-auditor')
  .description('Audit websites to generate branded, AI-ready CLAUDE.md fix briefs with Sanad Brand Gates.')
  .version('1.0.0')
  .argument('<url>', 'The target website URL to audit')
  .option('-s, --strategy <mobile|desktop>', 'Lighthouse audit strategy', 'mobile')
  .option('-o, --output <path>', 'Output markdown file path', 'CLAUDE.md')
  .action((url, options) => {
    console.log(`\n🧬 Starting Sanad Web Auditor on: ${url}...`);
    console.log(`⚡ Strategy: ${options.strategy}`);

    try {
      // 1. Run the upstream lighthouse-md tool
      console.log('🔄 Fetching Google PageSpeed Insights & generating raw audit plan...');
      const stdout = execSync(`npx lighthouse-md ${url} --strategy ${options.strategy} --stdout`, {
        encoding: 'utf-8',
        stdio: ['pipe', 'pipe', 'ignore'] // ignore stderr noise
      });

      if (!stdout || stdout.trim() === '') {
        throw new Error('Received empty response from PageSpeed audit.');
      }

      // 2. Prep the Sanad Branded header & Brand Gates
      const sanadHeader = `<!--
  Generated by Sanad Web Auditor (سند)
  Brand: Sanad (AI-assisted web automation and client solutions)
  Date: ${new Date().toISOString().split('T')[0]}
-->

# Sanad AI-Ready Fix Plan (CLAUDE.md)

> This document outlines the performance, accessibility, and SEO findings for **${url}** and provides prescriptive, actionable instructions for AI coding agents (Claude Code, Hermes, Cursor) to apply.

---

## 🛑 SANAD BRAND GATES & DESIGN GUIDELINES (MANDATORY)

Before executing any of the fixes below, you **MUST** adhere to the following Sanad organizational brand rules:

1. **No Living Beings (Faces/Crowds)**: Absolutely NO human faces or living beings in any visual/client-facing elements, placeholder images, or illustration SVGs. Maintain 100% abstract/product/architectural visuals.
2. **Bilingual Arabic/English (RTL)**: Ensure Arabic translations are fully supported with correct RTL text-direction tags (\`dir="rtl"\`). Use clean script-specific font stacks for Arabic (do not mirror Latin styling).
3. **Client-Facing Copy**: Keep all public-facing text in professional, diplomatic, AI-free English with **zero emojis** and one-word clean brand references. Never mention internal developer names in commits/comments.
4. **Mobile & Kiosk First**: Ensure touch targets are large (minimum 48px), contrast ratios pass WCAG AA, and there is absolutely zero horizontal overflow on mobile viewports.

---

`;

      const finalContent = sanadHeader + stdout;

      // 3. Write to the output file
      const outputPath = path.resolve(options.output);
      fs.writeFileSync(outputPath, finalContent, 'utf-8');

      console.log(`\n✅ Success! Branded AI-ready audit written to: ${outputPath}`);
      console.log('🚀 Feed this CLAUDE.md directly to your AI Agent or Claude Code to execute the fixes.');

    } catch (error) {
      console.error('\n❌ Audit Failed:', error.message);
      process.exit(1);
    }
  });

program.parse(process.argv);
